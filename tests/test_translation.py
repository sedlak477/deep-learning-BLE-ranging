def load_matlab_test_data():
    test_file = Path(__file__).parent / 'test_data_multi.json'
    if not test_file.exists():
        return []
    with open(test_file, 'r') as f:
        cases = json.load(f)
        # Ensure we return a list of tuples for pytest.mark.parametrize
        return [(c['name'], c['inputs'], c['outputs']) for c in cases]

MATLAB_CASES = load_matlab_test_data()

@pytest.mark.parametrize("name,inputs,expected", MATLAB_CASES)
def test_music_fb_alg_matlab_validation(name, inputs, expected):
    """
    Validates the Python translation of music_fb_alg directly against 
    the mathematically identical outputs generated by the original MATLAB/Octave script.
    """
    # Convert inputs to appropriate numpy arrays
    M = inputs['M']
    nsig = inputs['nsig']
    Nptot = inputs['Nptot']
    dists = np.array(inputs['dists'])
    cal_dist = inputs['cal_dist']
    threshold = inputs['threshold']
    S = np.array(inputs['S_real']) + 1j * np.array(inputs['S_imag'])
    CFR_data = np.array(inputs['CFR_data_real']) + 1j * np.array(inputs['CFR_data_imag'])

    # Call translated function
    dist_MUSIC, spec_dB, peakwidth = music_fb_alg(
        M, nsig, Nptot, dists, cal_dist, threshold, CFR_data, S
    )

    # Compare outputs
    expected_dist = np.array(expected['dist_MUSIC']).flatten()
    expected_spec = np.array(expected['spec_dB']).flatten()
    
    expected_peakwidth = expected['peakwidth']
    
    # Octave now natively returns width via findpeaks_compat wrapper
    np.testing.assert_allclose(dist_MUSIC.flatten(), expected_dist, rtol=1e-5, atol=1e-8, err_msg=f"{name}: dist_MUSIC mismatch")
    np.testing.assert_allclose(spec_dB.flatten(), expected_spec, rtol=1e-5, atol=1e-8, err_msg=f"{name}: spec_dB mismatch")
    if np.isinf(peakwidth):
        assert expected_peakwidth is None or expected_peakwidth == 0 or np.isinf(expected_peakwidth) or expected_peakwidth == 'Inf'
    else:
        np.testing.assert_allclose(peakwidth, expected_peakwidth, rtol=1e-5, atol=1e-5, err_msg=f"{name}: peakwidth mismatch")


