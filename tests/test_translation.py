def test_music_python_multi_antenna_symmetry():
    """
    Tests multi-antenna processing symmetry. A matrix with duplicated identical antennas 
    should produce mathematically identical covariance matrices and thus the exact same 
    spectrum as a single antenna of that data.
    """
    M, nsig, Nptot = 5, 2, 10
    dists = np.linspace(0, 10, 100)
    S = np.exp(1j * np.random.rand(M, 100))
    
    single_ant = np.random.randn(Nptot, 1) + 1j * np.random.randn(Nptot, 1)
    # Duplicate antenna columns
    multi_ant = np.hstack([single_ant, single_ant, single_ant])
    
    dist1, spec1, width1 = music_fb_alg(M, nsig, Nptot, dists, 0, -10, single_ant, S)
    dist2, spec2, width2 = music_fb_alg(M, nsig, Nptot, dists, 0, -10, multi_ant, S)
    
    np.testing.assert_allclose(spec1, spec2, rtol=1e-5, atol=1e-8, err_msg="Multi-antenna symmetry failed")
    np.testing.assert_allclose(dist1, dist2, rtol=1e-5, atol=1e-8, err_msg="Distances differed between symmetrical arrays")

def test_music_python_end_to_end_ranging():
    """
    Tests the algorithm end-to-end using physically generated IQ samples for a known distance.
    This simulates a real BLE two-way ranging signal and verifies the algorithm returns the correct physical distance.
    """
    from tests.gen_ch import gen_ch
    
    # Physics parameters
    dist_LOS = 15.0 # 15 meters
    c = 3e8
    delta_f = 1e6
    n = np.arange(-37, 38)
    Nptot = len(n)
    
    # Generate channel data (high SNR to ensure exact peak match)
    SNR = 40 
    CFR_data_array = gen_ch(num_runs=1, SNR=SNR, dist_vec=[dist_LOS], att_vec=[1.0], 
                            n=n, delta_f=delta_f, c=c, rayleigh=False)
    CFR_data = CFR_data_array[:, 0]
    
    # MUSIC parameters
    M = 15 # Subarray size
    nsig = 5
    taus = np.arange(0, 50, 0.001) / c # search space up to 50m
    dists = taus * c
    
    # Recreate the exact steering vector mathematically
    # S has dimensions M x len(taus)
    S = np.exp(-1j * 2 * np.pi * delta_f * np.outer(n[:M], taus))
    
    # Run the MUSIC algorithm
    dist_MUSIC, spec_dB, peakwidth = music_fb_alg(
        M, nsig, Nptot, dists, 0, -13, CFR_data, S
    )
    
    # In a two-way channel simulation, the delay/distance computed is round-trip
    estimated_distance = dist_MUSIC[0] / 2.0
    
    # Verify the estimation matches the physics input!
    np.testing.assert_allclose(estimated_distance, dist_LOS, rtol=1e-2, atol=0.1, 
                               err_msg=f"End-to-End ranging failed. Expected {dist_LOS}m, got {estimated_distance}m")

def test_gen_ch_translation():
    """
    Compares IQ sample data generated by Python gen_ch.py against the exact output 
    from MATLAB gen_ch.m to ensure the translation is mathematically identical.
    """
    from tests.gen_ch import gen_ch
    
    test_file = Path(__file__).parent / 'gen_ch_data.json'
    if not test_file.exists():
        pytest.skip("gen_ch_data.json not found.")
        
    with open(test_file, 'r') as f:
        data = json.load(f)
        
    inputs = data['inputs']
    expected_real = np.array(data['CFR_data_array_real'])
    expected_imag = np.array(data['CFR_data_array_imag'])
    expected_cfr = expected_real + 1j * expected_imag
    
    # Run the Python implementation
    python_cfr = gen_ch(
        num_runs=inputs['num_runs'],
        SNR=inputs['SNR'],
        dist_vec=np.array(inputs['dist_vec']).flatten(),
        att_vec=np.array(inputs['att_vec']).flatten(),
        n=np.array(inputs['n']).flatten(),
        delta_f=inputs['delta_f'],
        c=inputs['c'],
        rayleigh=inputs['rayleigh']
    )
    
    # Assert equivalence. Since SNR=300, noise is near zero.
    # Tolerances are tight because it's deterministic physics calculation.
    np.testing.assert_allclose(python_cfr, expected_cfr, rtol=1e-5, atol=1e-8,
                               err_msg="Python gen_ch output differs from MATLAB gen_ch.m")

