def test_music_python_flat_spectrum():
    """
    Tests the scenario where CFR_data is purely white noise, ensuring 
    the spectrum calculation doesn't crash or return NaNs.
    """
    M, nsig, Nptot = 5, 2, 10
    dists = np.linspace(0, 10, 100)
    S = np.exp(1j * np.random.rand(M, 100))
    # Pure white noise
    CFR_data = np.random.randn(Nptot, 1) + 1j * np.random.randn(Nptot, 1)
    
    dist_MUSIC, spec_dB, peakwidth = music_fb_alg(M, nsig, Nptot, dists, 0, -10, CFR_data, S)
    
    # Check shape correctness
    assert dist_MUSIC.shape[0] == nsig, "Output distances should pad/truncate to nsig"
    assert spec_dB.shape == (1, 100), "Spectrum should be shape (1, num_dists)"
    assert not np.any(np.isnan(spec_dB)), "Spectrum should not contain NaNs"


